/** An icon by its `windows` name, filled when there is a filled variant. */
export const fluentIcon = (name: SystemIconWindowsName, filled = false) =>
  (filled && filledIcons[name.replace(/Regular$/, 'Filled')]) ||
  fluentIcons[name];
